# Trim, downscale and measure every cut-out -> public/sun/*.png + src/sun/sprites.ts
import json, numpy as np, cv2
from PIL import Image
RAW='images/sun/raw'; OUT='public/sun'
MAXDIM={'hero':1700,'worried':1700,'brace':1700,'windup':1700,'follow':1700,'cheer':1700,'facepalm':1900,
        'rocket':1000,'earth':1700,'sun':2600,'mars':900,'venus':1100}
CHAR={'hero','worried','brace','windup','follow','cheer','facepalm'}
info={}
for n,md in MAXDIM.items():
    im=Image.open(f'{RAW}/{n}.png').convert('RGBA'); a=np.array(im)
    ys,xs=np.where(a[:,:,3]>8); x0,x1,y0,y1=xs.min(),xs.max(),ys.min(),ys.max()
    pad=12; x0=max(0,x0-pad); y0=max(0,y0-pad); x1=min(a.shape[1]-1,x1+pad); y1=min(a.shape[0]-1,y1+pad)
    crop=im.crop((x0,y0,x1+1,y1+1)); s=min(1.0, md/max(crop.size))
    crop=crop.resize((round(crop.width*s),round(crop.height*s)),Image.LANCZOS); crop.save(f'{OUT}/{n}.png',optimize=True)
    A=np.array(crop); al=A[:,:,3]; h,w=al.shape
    d={'w':w,'h':h}
    a8=(al>128).astype(np.uint8); ff=a8.copy()
    cv2.floodFill(ff,np.zeros((h+2,w+2),np.uint8),(0,0),2)
    solid=np.where(ff==2,0,1).astype(np.uint8)
    if n in CHAR:
        dt=cv2.distanceTransform(solid,cv2.DIST_L2,5); hy,hx=np.unravel_index(dt.argmax(),dt.shape)
        d['head']=[int(hx),int(hy),float(round(dt[hy,hx],1))]
        rows=np.where(solid.any(1))[0]; bot=rows.max(); band=solid[int(bot-0.035*h):bot+1]
        fx=np.where(band.any(0))[0]; d['feet']=[float((fx.min()+fx.max())/2),int(bot)]
        # red rocket parts held in the hand
        rgb=A[:,:,:3].astype(int); red=(rgb[:,:,0]>170)&(rgb[:,:,1]<90)&(rgb[:,:,2]<90)&(al>200)
        if red.sum()>500:
            yy,xx=np.where(red); pts=np.stack([xx,yy],1).astype(float); c=pts.mean(0)
            ev,evec=np.linalg.eigh(np.cov((pts-c).T)); ax=evec[:,1]
            if ax[1]>0: ax=-ax          # point to nose (up)
            proj=(pts-c)@ax; d['rocket']={'c':[float(c[0]),float(c[1])],'len':float(proj.max()-proj.min()),
                 'angle':float(np.degrees(np.arctan2(ax[0],-ax[1])))}
        ys2,xs2=np.where(al>128); k=np.argmax(xs2-ys2); d['upright']=[int(xs2[k]),int(ys2[k])]
    else:
        ys2,xs2=np.where(solid>0); d['c']=[float((xs2.min()+xs2.max())/2),float((ys2.min()+ys2.max())/2)]
        d['r']=float((xs2.max()-xs2.min()+ys2.max()-ys2.min())/4)
        if n=='sun':   # inner disc radius: largest inscribed circle
            dt=cv2.distanceTransform(solid,cv2.DIST_L2,5); hy,hx=np.unravel_index(dt.argmax(),dt.shape)
            d['disc']=[int(hx),int(hy),float(dt[hy,hx])]
        if n=='rocket':
            rgb=A[:,:,:3].astype(int); red=(rgb[:,:,0]>170)&(rgb[:,:,1]<90)&(rgb[:,:,2]<90)&(al>200)
            yy,xx=np.where(red); d['redLen']=float(yy.max()-yy.min()); d['redC']=[float(xx.mean()),float(yy.mean())]
            d['top']=int(ys2.min()); d['bottom']=int(ys2.max())
    info[n]=d
open('src/sun/sprites.ts','w').write('// generated by images/sun/prep.py\nexport const SPR = '+json.dumps(info,indent=1)+' as const;\n')
print(json.dumps(info,indent=0)[:3000])
